// Copies the Men calendar / question-generator code and Quran data from src/ into the Edge Functions'
// shared folder, rewriting imports to Deno form. Edge Functions deploy from supabase/functions only.
//   node scripts/sync-edge-shared.mjs          # write
//   node scripts/sync-edge-shared.mjs --check  # fail if the copies are out of date
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(new URL("..", import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1"));
const out = path.join(root, "supabase/functions/_shared/men");
const check = process.argv.includes("--check");

const files = [
  ["src/types.ts", "types.ts"],
  ["src/lib/calculations.ts", "calculations.ts"],
  ["src/lib/difficulty.ts", "difficulty.ts"],
  ["src/lib/testGenerator.ts", "testGenerator.ts"],
  ["src/lib/authIdentity.ts", "authIdentity.ts"],
  ["src/lib/menRows.ts", "menRows.ts"],
  ["src/lib/menData.ts", "menData.ts"],
  ["src/data/mushafLines.json", "data/mushafLines.json"],
  ["src/data/quranQuarters.json", "data/quranQuarters.json"],
];

const header = "// GENERATED by scripts/sync-edge-shared.mjs from src/ — edit the source file, then re-run the script.\n";

function denoize(source) {
  return (
    header +
    source
      .replace(/from '\.\.\/data\/([\w]+)\.json';/g, "from './data/$1.json' with { type: 'json' };")
      .replace(/from '\.\.\/types';/g, "from './types.ts';")
      .replace(/from '\.\/(difficulty|calculations|testGenerator|authIdentity|menRows|menData)';/g, "from './$1.ts';")
  );
}

let stale = [];
for (const [src, dest] of files) {
  const input = fs.readFileSync(path.join(root, src), "utf8");
  const expected = dest.endsWith(".json") ? input : denoize(input);
  const target = path.join(out, dest);
  const current = fs.existsSync(target) ? fs.readFileSync(target, "utf8") : null;
  if (current === expected) continue;
  if (check) stale.push(dest);
  else {
    fs.mkdirSync(path.dirname(target), { recursive: true });
    fs.writeFileSync(target, expected);
  }
}
if (check && stale.length) {
  console.error(`Edge shared copies are out of date: ${stale.join(", ")}. Run: node scripts/sync-edge-shared.mjs`);
  process.exitCode = 1;
} else {
  console.log(check ? "Edge shared copies are up to date." : `Synced ${files.length} files to ${path.relative(root, out)}`);
}
